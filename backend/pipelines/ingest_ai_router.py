"""
Autonomous Background Ingestion Pipeline & AI Router.

Features:
- Project-wide directory scanner targeting dataset files (.json, .csv, .db, .parquet, .tsv).
- Resumable manifest tracking (file-level and record-level) in darknight.db.
- Atomic database transactions preventing duplicates or data loss on process restart.
- Hybrid Classifier Engine:
  - Uses Anthropic API when ANTHROPIC_API_KEY is present.
  - Falls back to offline heuristic classifier when API key is absent, tagging metadata with {"classified_by": "heuristic"}.
- Auto-creation of dynamic EntityTypes and ActivityTypes recorded in backend/data/canonical_schema_extensions.py.
- Prominent logging of identifier collisions to identifier_collisions.log.
- CLI interface and FastAPI background task integration.
"""

